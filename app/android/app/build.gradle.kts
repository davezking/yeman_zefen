// AdMob app ids per flavor, for the manifest (docs/ops.md, Ads). Dev uses Google's sample app id.
// Prod uses it too until the AdMob app exists; prod shows no ads while its ad units in
// config/prod.json are empty.
val admobAppIds = mapOf(
    "dev" to "ca-app-pub-3940256099942544~3347511713",
    "prod" to "ca-app-pub-3940256099942544~3347511713",
)
android.productFlavors.configureEach {
    manifestPlaceholders["admobAppId"] = admobAppIds.getValue(name)
    // Only prod release builds upload their R8 mapping file to Crashlytics; dev (and CI) builds skip it.
    val flavorName = name
    (this as ExtensionAware).extensions.configure<CrashlyticsExtension> {
        mappingFileUploadEnabled = flavorName == "prod"
    }
}
